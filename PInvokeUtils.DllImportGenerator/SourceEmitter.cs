using System;
using System.Collections.Generic;
using System.Linq;
using System.Runtime.InteropServices;
using System.Text;

namespace PlatformInvokeGenerator;

/// <summary>
/// Generates the source of the class with platform specific extern methods and call methods.
/// The generated code is fully qualified and uses C# 7.3 syntax only.
/// </summary>
internal static class SourceEmitter
{
    const string INTEROP = "global::System.Runtime.InteropServices";

    //architecture specific imports per OS, checked in this order before the OS fallback import
    static readonly (ImportPlatform Platform, string Architecture)[] WINDOWS_ARCHITECTURES = { (ImportPlatform.WinArm64, nameof(Architecture.Arm64)) };
    static readonly (ImportPlatform Platform, string Architecture)[] LINUX_ARCHITECTURES = { (ImportPlatform.LinuxArm64, nameof(Architecture.Arm64)) };
    static readonly (ImportPlatform Platform, string Architecture)[] OSX_ARCHITECTURES = { (ImportPlatform.OsxArm64, nameof(Architecture.Arm64)),
                                                                                           (ImportPlatform.OsxX64, nameof(Architecture.X64)) };

    public static string Emit(in ClassInfo cl, bool supportsNullable)
    {
        var w = new CodeWriter();
        w.Line("//------------------------------------------------------------------------------")
         .Line("// <auto-generated>")
         .Line("//     This code was generated by the PlatformInvokeGenerator source generator")
         .Line("//")
         .Line("//     Changes to this file may cause incorrect behavior and will be lost if")
         .Line("//     the code is regenerated.")
         .Line("// </auto-generated>")
         .Line("//------------------------------------------------------------------------------")
         .Line()
         .Line("#pragma warning disable");
        //generated signatures are nullable oblivious, so callers get no nullable warnings
        if (supportsNullable)
            w.Line("#nullable disable");
        w.Line();

        if (cl.Namespace is not null)
            w.Line("namespace " + cl.Namespace).Open();
        foreach (var containingType in cl.ContainingTypes)
            w.Line(containingType).Open();

        w.Line(cl.ClassDeclaration).Open();

        for (var i = 0; i < cl.Methods.Length; i++)
        {
            if (i > 0)
                w.Line();
            EmitMethodGroup(w, cl.Methods[i], cl);
        }

        EmitStringHelpers(w, cl);

        w.Close();
        foreach (var _ in cl.ContainingTypes)
            w.Close();
        if (cl.Namespace is not null)
            w.Close();

        return w.ToString();
    }

    static void EmitMethodGroup(CodeWriter w, in MethodGroup method, in ClassInfo cl)
    {
        var imports = new Dictionary<ImportPlatform, ImportInfo>();
        foreach (var import in method.Imports)
        {
            var dllImport = new StringBuilder(INTEROP + ".DllImportAttribute(")
                .Append(ModelBuilder.FormatStringLiteral(import.DllName))
                .Append(", EntryPoint = ").Append(ModelBuilder.FormatStringLiteral(import.EntryPoint))
                .Append(", CallingConvention = " + INTEROP + ".CallingConvention.").Append(import.CallingConvention);
            if (import.CharSet is not CharSet.None and not CharSet.Ansi)
                dllImport.Append(", CharSet = " + INTEROP + ".CharSet.").Append(import.CharSet);
            if (import.SetLastError)
                dllImport.Append(", SetLastError = true");
            dllImport.Append(')');

            w.Line("[" + dllImport + "]");
            if (method.ReturnAttributes.Length > 0)
                w.Line("[return: " + method.ReturnAttributes + "]");
            w.Line($"private static extern {method.ReturnType} {ExternName(import.Platform, method.Name)}({RenderExternParameters(method, import)});")
             .Line();

            imports[import.Platform] = import;
        }

        var parameters = string.Join(", ", method.Parameters.Select(p => p.Render()));
        if (method.PartialModifiers is not null)
            w.Line($"{method.PartialModifiers} {method.ReturnType} {ModelBuilder.EscapeIdentifier(method.Name)}({method.ImplementationParameters})").Open();
        else
            w.Line($"{cl.CallMethodsAccessModifier}{(method.IsStatic ? " static" : "")} {method.ReturnType} {(cl.UseImplSuffix ? method.Name + "Impl" : ModelBuilder.EscapeIdentifier(method.Name))}({parameters})").Open();

        //stub of a partial method with errors (no imports), the error itself is reported by the generator
        if (imports.Count == 0)
        {
            w.Line("throw new global::System.NotSupportedException(\"The method has PlatformInvokeGenerator errors\");").Close();
            return;
        }

        var @return = method.ReturnType == "void" ? "" : "return ";
        var group = method;
        var generatedClass = cl;
        Action<ImportPlatform> call = platform => EmitCall(w, generatedClass, group, imports[platform], @return);

        var platforms = new HashSet<ImportPlatform>(imports.Keys);
        var hasWindows = platforms.Overlaps(WINDOWS_PLATFORMS);
        var hasLinux = platforms.Overlaps(LINUX_PLATFORMS);
        var hasOsx = platforms.Overlaps(OSX_PLATFORMS);

        //single platform, no runtime checks
        if (platforms.Count == 1)
            call(platforms.First());
        //windows only, the OS check is skipped
        else if (IsWindowsOnly(platforms))
            EmitWindowsCall(w, platforms, call);
        else
        {
            var branch = "if";
            if (hasWindows)
            {
                OpenOsBranch(w, ref branch, nameof(OSPlatform.Windows));
                EmitWindowsCall(w, platforms, call);
                w.Close();
            }
            if (hasLinux)
            {
                OpenOsBranch(w, ref branch, nameof(OSPlatform.Linux));
                EmitArchitectureSwitch(w, platforms, call, LINUX_ARCHITECTURES, Fallback(ImportPlatform.Linux64));
                w.Close();
            }
            if (hasOsx)
            {
                OpenOsBranch(w, ref branch, nameof(OSPlatform.OSX));
                EmitArchitectureSwitch(w, platforms, call, OSX_ARCHITECTURES, Fallback(ImportPlatform.Osx));
                w.Close();
            }
            w.Line("else")
             .Indented("throw new global::System.NotSupportedException(\"Current OSPlatform is not supported\");");
        }

        w.Close();

        Action? Fallback(ImportPlatform platform) => imports.ContainsKey(platform) ? () => call(platform) : null;
    }

    /// <summary>
    /// How the string parameters (passed by value, without MarshalAs) are passed to the import.
    /// </summary>
    enum StringConversion
    {
        //standard P/Invoke marshalling (CharSet)
        None,
        //wchar_t on Windows is UTF-16, the runtime passes the string without a copy
        Utf16,
        //pinned UTF-8 copy
        Utf8,
        //pinned UTF-32 copy (wchar_t on Linux and macOS)
        Utf32,
    }

    static StringConversion GetConversion(ImportInfo import) => import.StringMarshalling switch
    {
        NativeStringMarshalling.Utf8 => StringConversion.Utf8,
        NativeStringMarshalling.WideChar => WINDOWS_PLATFORMS.Contains(import.Platform) ? StringConversion.Utf16 : StringConversion.Utf32,
        _ => StringConversion.None,
    };

    /// <summary>
    /// The import gets converted copies of the string parameters.
    /// </summary>
    static bool NeedsCopy(in MethodGroup method, ImportInfo import)
        => GetConversion(import) is StringConversion.Utf8 or StringConversion.Utf32 && method.Parameters.Any(p => p.IsPlainString);

    /// <summary>
    /// Parameters of the platform import. The default values are left out, the import is private and the call method always passes all
    /// arguments (a byte array cannot have the default value of a string and a required parameter cannot follow optional ones, CS1737).
    /// </summary>
    static string RenderExternParameters(in MethodGroup method, ImportInfo import)
    {
        var conversion = GetConversion(import);
        var copy = NeedsCopy(method, import);
        return string.Join(", ", method.Parameters.Select(p => p.IsPlainString && copy ? "byte[] " + p.Name
                                                              : p.IsPlainString && conversion == StringConversion.Utf16 ? $"[{INTEROP}.MarshalAsAttribute({INTEROP}.UnmanagedType.LPWStr)] " + p.RenderWithoutDefault()
                                                              : p.RenderWithoutDefault()));
    }

    static void EmitCall(CodeWriter w, in ClassInfo cl, in MethodGroup method, ImportInfo import, string @return)
    {
        var externName = ExternName(import.Platform, method.Name);
        //one exactly sized array per converted string
        var encode = !NeedsCopy(method, import) ? null
                   : GetConversion(import) == StringConversion.Utf8 ? $"{EncodeHelperName(cl)}({{0}}, global::System.Text.Encoding.UTF8, 1)"
                   : $"{EncodeHelperName(cl)}({{0}}, global::System.Text.Encoding.UTF32, 4)";
        w.Line($"{@return}{externName}({string.Join(", ", method.Parameters.Select(p => encode != null && p.IsPlainString ? string.Format(encode, p.Name) : p.ArgumentModifier + p.Name))});");
    }

    /// <summary>
    /// Name of the string conversion helper, unique per source class (more source classes can generate into one partial class).
    /// </summary>
    static string EncodeHelperName(in ClassInfo cl)
        => "__PlatformInvokeGenerator_Encode_" + new string(cl.HintName.Replace(".g.cs", "").Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

    static void EmitStringHelpers(CodeWriter w, in ClassInfo cl)
    {
        if (!cl.Methods.Any(m => m.Imports.Any(i => NeedsCopy(m, i))))
            return;

        w.Line()
         .Line($"private static byte[] {EncodeHelperName(cl)}(string value, global::System.Text.Encoding encoding, int terminatorSize)").Open()
         .Line("if (value == null)")
         .Indented("return null;")
         .Line("//the terminator is already zero")
         .Line("var bytes = new byte[encoding.GetByteCount(value) + terminatorSize];")
         .Line("encoding.GetBytes(value, 0, value.Length, bytes, 0);")
         .Line("return bytes;")
         .Close();
    }

    static string ExternName(ImportPlatform platform, string methodName) => "__" + platform + "_" + methodName;

    static readonly ImportPlatform[] WINDOWS_PLATFORMS = { ImportPlatform.Win32, ImportPlatform.Win64, ImportPlatform.WinArm64 };
    static readonly ImportPlatform[] LINUX_PLATFORMS = { ImportPlatform.Linux64, ImportPlatform.LinuxArm64 };
    static readonly ImportPlatform[] OSX_PLATFORMS = { ImportPlatform.Osx, ImportPlatform.OsxX64, ImportPlatform.OsxArm64 };

    static bool IsWindowsOnly(ICollection<ImportPlatform> platforms)
        => platforms.Overlaps(WINDOWS_PLATFORMS) && !platforms.Overlaps(LINUX_PLATFORMS) && !platforms.Overlaps(OSX_PLATFORMS);

    /// <summary>
    /// True when the generated call method checks the OS or the process architecture by RuntimeInformation.
    /// A single import needs no check, Win32 + Win64 only are distinguished by Environment.Is64BitProcess.
    /// </summary>
    public static bool RequiresRuntimeInformation(ICollection<ImportPlatform> platforms)
    {
        if (platforms.Count <= 1)
            return false;
        if (IsWindowsOnly(platforms))
            return platforms.Contains(ImportPlatform.WinArm64);
        return true;
    }

    static void OpenOsBranch(CodeWriter w, ref string branch, string osPlatform)
    {
        w.Line($"{branch}({INTEROP}.RuntimeInformation.IsOSPlatform({INTEROP}.OSPlatform.{osPlatform}))").Open();
        branch = "else if";
    }

    static void EmitWindowsCall(CodeWriter w, HashSet<ImportPlatform> platforms, Action<ImportPlatform> call)
    {
        Action? bitnessCall = null;
        if (platforms.Contains(ImportPlatform.Win32) && platforms.Contains(ImportPlatform.Win64))
            bitnessCall = () =>
            {
                w.Line("if(global::System.Environment.Is64BitProcess)").Open();
                call(ImportPlatform.Win64);
                w.Close().Line("else").Open();
                call(ImportPlatform.Win32);
                w.Close();
            };
        else if (platforms.Contains(ImportPlatform.Win32) || platforms.Contains(ImportPlatform.Win64))
            bitnessCall = () => call(platforms.Contains(ImportPlatform.Win64) ? ImportPlatform.Win64 : ImportPlatform.Win32);

        EmitArchitectureSwitch(w, platforms, call, WINDOWS_ARCHITECTURES, bitnessCall);
    }

    /// <summary>
    /// Calls the architecture specific imports of one OS, the fallback is called when none of the architectures matches.
    /// Without a fallback NotSupportedException is thrown.
    /// </summary>
    static void EmitArchitectureSwitch(CodeWriter w,
                                       HashSet<ImportPlatform> platforms,
                                       Action<ImportPlatform> call,
                                       (ImportPlatform Platform, string Architecture)[] architectures,
                                       Action? fallback)
    {
        var present = architectures.Where(x => platforms.Contains(x.Platform)).ToArray();

        //no architecture specific import, no need to check the process architecture
        if (present.Length == 0)
        {
            fallback!();
            return;
        }

        var branch = "if";
        foreach (var (platform, architecture) in present)
        {
            w.Line($"{branch}({INTEROP}.RuntimeInformation.ProcessArchitecture == {INTEROP}.Architecture.{architecture})").Open();
            call(platform);
            w.Close();
            branch = "else if";
        }

        w.Line("else");
        if (fallback is not null)
        {
            w.Open();
            fallback();
            w.Close();
        }
        else
            w.Indented("throw new global::System.NotSupportedException(\"Current process architecture is not supported\");");
    }

    static bool Overlaps(this ICollection<ImportPlatform> platforms, ImportPlatform[] other) => other.Any(platforms.Contains);

    sealed class CodeWriter
    {
        readonly StringBuilder _sb = new();
        int _indent;

        public CodeWriter Line(string line = "")
        {
            if (line.Length > 0)
                _sb.Append(' ', _indent * 4);
            _sb.Append(line).Append('\n');
            return this;
        }

        public CodeWriter Indented(string line)
        {
            _indent++;
            Line(line);
            _indent--;
            return this;
        }

        public CodeWriter Open()
        {
            Line("{");
            _indent++;
            return this;
        }

        public CodeWriter Close()
        {
            _indent--;
            return Line("}");
        }

        public override string ToString() => _sb.ToString();
    }
}
